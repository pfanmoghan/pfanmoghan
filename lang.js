function setLanguage(lang) {
  const t = translations[lang];
  if (!t) return;

  // Update html attributes
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr';
  document.body.classList.toggle('ltr', lang === 'en');

  // Update all elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      if (el.tagName === 'TITLE') {
        document.title = t[key];
      } else if (el.hasAttribute('data-i18n-html') || t[key].includes('<br>')) {
        el.innerHTML = t[key];
      } else {
        el.textContent = t[key];
      }
    }
  });

  // Update title if present
  const titleEl = document.querySelector('title');
  if (titleEl && titleEl.hasAttribute('data-i18n')) {
    document.title = t[titleEl.getAttribute('data-i18n')] || document.title;
  }

  // Save preference
  localStorage.setItem('lang', lang);

  // Update switcher buttons active state
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
}

// Initialize on page load
document.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('lang') || 'fa';
  setLanguage(saved);

  // Attach click handlers
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      setLanguage(btn.dataset.lang);
    });
  });
});
